using System.Collections;
using System.Collections.Generic;
using UnityEngine;

// The AudioSource on this object is the template the two tracks copy (volume, mixer group).
[RequireComponent(typeof(AudioSource))]
public class LevelSelectMusicController : MonoBehaviour
{
    public static LevelSelectMusicController Instance;

    [SerializeField] private LevelSelectDesignerData data;

    public bool playOnStart = true;

    [Tooltip("Seconds node music takes to fade back in when a camera sequence finishes and lets it go. 0 = straight in.")]
    [Min(0f)] public float fadeInAfterSequence = 4f;

    private AudioSource _source;
    // The AudioSource's own volume — what every fade climbs back to.
    private float _baseVolume;

    // Held while a camera sequence plays its own audio. Holds stack; node music comes back when the last one lets go.
    // The starting audio is never held — it plays under the intro.
    private int _holds;

    // ── Starting audio and node music ─────────────────────────────
    // The starting audio plays from the start. A node with Audio on crossfades whatever is playing
    // into its own music when the boat sails into the box across the river there
    // (LevelSelectMusicTrigger, generated by the designer). Two sources, swapped each crossfade.
    private readonly AudioSource[] _tracks = new AudioSource[2];
    private readonly Coroutine[]   _trackFades = new Coroutine[2];
    private int    _current = -1;
    private bool   _currentIsStart;
    private string _currentNodeId;
    private bool   _trackPausedByHold;

    private readonly List<LevelSelectDesignerData.DesignerNode> _triggers = new();

    // The last node whose music played. It outlives the scene: back from a level, the level
    // select starts on that music rather than the starting audio. Session only — a fresh launch starts on the starting audio.
    private static string s_lastNodeId;

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
    private static void ResetSession() => s_lastNodeId = null;

    public bool IsHeld => _holds > 0;

    private void Awake()
    {
        Instance = this;
        _source = GetComponent<AudioSource>();
        _baseVolume = _source.volume;
    }

    private void Start()
    {
        if (!playOnStart || data == null) return;

        CollectTriggers();

        var last = _triggers.Find(n => n.id == s_lastNodeId);
        if (last != null)
        {
            Debug.Log($"[LevelSelectMusic] Back in the level select — resuming node {last.id}'s music {last.musicClip.name}.");
            CrossfadeTo(last.musicClip, last.musicLooped, 0f, false, last.id);
        }
        else if (data.startingAudio != null)
        {
            Debug.Log($"[LevelSelectMusic] Starting audio: {data.startingAudio.name} " +
                      $"{(data.startingAudioLooped ? "looping" : "once")}, fade in {data.startingAudioFadeIn:F1}s, {_triggers.Count} node(s) with Audio.");
            CrossfadeTo(data.startingAudio, data.startingAudioLooped, data.startingAudioFadeIn, true, null);
        }
    }

    /// <summary>The boat sailed into a node's box (LevelSelectMusicTrigger).</summary>
    public void BoatEntered(string nodeId)
    {
        if (nodeId == _currentNodeId) return;

        var node = _triggers.Find(n => n.id == nodeId);
        if (node == null) return;   // Audio off since the box was built, or no clip — said at Start

        s_lastNodeId = node.id;
        // The same song on another node carries straight on.
        if (_current >= 0 && _tracks[_current].clip == node.musicClip && !_currentIsStart)
        {
            _currentNodeId = node.id;
            return;
        }

        Debug.Log($"[LevelSelectMusic] Boat reached node {node.id} — crossfading to {node.musicClip.name} over {node.musicCrossfade:F1}s.");
        CrossfadeTo(node.musicClip, node.musicLooped, node.musicCrossfade, false, node.id);
    }

    private void CollectTriggers()
    {
        _triggers.Clear();
        foreach (var node in data.nodes)
        {
            if (node == null || !node.musicTrigger) continue;
            if (node.musicClip == null)
            {
                Debug.LogWarning($"[LevelSelectMusic] Node {node.id} has Audio on but no music clip — skipped.");
                continue;
            }
            _triggers.Add(node);
        }

        // The boxes are built by the designer, so a node switched on since the last Generate has none.
        var boxes = new HashSet<string>();
        foreach (var box in FindObjectsByType<LevelSelectMusicTrigger>(FindObjectsSortMode.None))
            boxes.Add(box.nodeId);
        foreach (var node in _triggers)
            if (!boxes.Contains(node.id))
                Debug.LogWarning($"[LevelSelectMusic] Node {node.id} has Audio on but no box across the " +
                                 "river in the scene — Generate in the Level Select Designer to build it.");

        if (data.startingAudio != null && data.startingAudioLooped && _triggers.Count == 0)
            Debug.LogWarning("[LevelSelectMusic] Starting audio loops but no river node has Audio on — it will never stop.");
    }

    private void CrossfadeTo(AudioClip clip, bool loop, float duration, bool isStart, string nodeId)
    {
        int prev = _current;
        int next = prev == 0 ? 1 : 0;

        if (_tracks[next] == null) _tracks[next] = AddTrackSource();
        var src = _tracks[next];
        StopTrackFade(next);
        src.clip   = clip;
        src.loop   = loop;
        src.volume = duration > 0f ? 0f : _baseVolume;
        src.Play();

        _current        = next;
        _currentIsStart = isStart;
        _currentNodeId  = nodeId;
        _trackPausedByHold = false;

        if (prev >= 0)
        {
            StopTrackFade(prev);
            if (duration > 0f) _trackFades[prev] = StartCoroutine(FadeTrack(prev, 0f, duration, true));
            else _tracks[prev].Stop();
        }

        // Music arriving while a camera sequence holds waits for it to let go. The starting audio never waits.
        if (!isStart && IsHeld)
        {
            src.Pause();
            _trackPausedByHold = true;
            return;
        }
        if (duration > 0f) _trackFades[next] = StartCoroutine(FadeTrack(next, _baseVolume, duration, false));
    }

    private AudioSource AddTrackSource()
    {
        var src = gameObject.AddComponent<AudioSource>();
        src.playOnAwake           = false;
        src.outputAudioMixerGroup = _source.outputAudioMixerGroup;
        src.spatialBlend          = _source.spatialBlend;
        src.priority              = _source.priority;
        return src;
    }

    private void StopTrackFade(int i)
    {
        if (_trackFades[i] != null) StopCoroutine(_trackFades[i]);
        _trackFades[i] = null;
    }

    private IEnumerator FadeTrack(int i, float to, float duration, bool stopAtEnd)
    {
        var src = _tracks[i];
        float from = src.volume;
        float elapsed = 0f;
        while (elapsed < duration)
        {
            elapsed += Time.deltaTime;
            src.volume = Mathf.Lerp(from, to, elapsed / duration);
            yield return null;
        }
        src.volume = to;
        if (stopAtEnd) src.Stop();
        _trackFades[i] = null;
    }

    /// <summary>Pause node music (or keep it from starting) until Release. The starting audio plays on.</summary>
    public void Hold()
    {
        _holds++;
        if (_holds > 1) return;

        if (_current >= 0 && !_currentIsStart && _tracks[_current].isPlaying)
        {
            StopTrackFade(_current);
            _tracks[_current].volume = _baseVolume;
            _tracks[_current].Pause();
            _trackPausedByHold = true;
        }
        Debug.Log($"[LevelSelectMusic] Hold: {(_trackPausedByHold ? "paused" : "nothing to pause")}.");
    }

    /// <summary>Let go of a Hold — node music picks up where it paused.</summary>
    public void Release()
    {
        if (_holds == 0) return;
        if (--_holds > 0) return;

        if (_trackPausedByHold && _current >= 0)
        {
            _trackPausedByHold = false;
            var src = _tracks[_current];
            src.volume = fadeInAfterSequence > 0f ? 0f : _baseVolume;
            src.UnPause();
            StopTrackFade(_current);
            if (fadeInAfterSequence > 0f)
                _trackFades[_current] = StartCoroutine(FadeTrack(_current, _baseVolume, fadeInAfterSequence, false));
            Debug.Log($"[LevelSelectMusic] Release: node {_currentNodeId}'s music resumed, fade in {fadeInAfterSequence:F1}s.");
        }
    }
}
